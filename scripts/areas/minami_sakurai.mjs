// 出典:
// - 南桜井村と地名由来: 明治22年(1889年)、古代からの呼称「桜井郷」にちなみ、大衾・金崎・上金崎・西金野井・永沼・上柳・下柳の7か村が合併して「南桜井村」が誕生（同郡内に既に別の桜井村があったため「南」を冠した）。一方、現在の駅がある「米島（こめじま）」は隣接する「川辺村」に属していた。
// - 南桜井駅と米島駅の統合: 昭和5年(1930年)に永沼臨時停留所として開設、昭和7年(1932年)に「南桜井駅」と改称。太平洋戦争中の昭和18年(1943年)、服部時計店（精工舎）の疎開工場建設に伴い現在地（米島）に貨物専用の「米島仮停車場（米島駅）」が開設された。昭和29年(1954年)に南桜井村・川辺村・富多村・宝珠花村が合併して「庄和村（のち庄和町）」となった後、昭和31年(1956年)に南桜井駅と米島駅が現在地で統合され「南桜井駅」となった。
// - 御菓子司 新柳（春日部市米島1198-5）: 昭和47年(1972年)創業、南桜井駅南口近くの和菓子店。春日部市の鳥・都鳥の焼き印を押した「春日部ラムレーズン」や栗どら焼き等を製造販売。
