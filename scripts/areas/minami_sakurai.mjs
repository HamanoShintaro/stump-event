// - 米島香取神社（春日部市米島1-1）: 室町時代の文明年間(1469〜1487年)以前からの創建と伝わる、米島など近郷5か村の総社。境内に推定樹齢800年の大椋（ムクノキ）がそびえ、毎年2月に「甘酒祭り」が行われる。
// - 弥勒山 蓮花院（春日部市大衾53）: 真言宗豊山派。境内から嘉暦2年(1327年)銘の板碑が出土した鎌倉時代からの古刹で、本堂は宝永8年(1711年)建立。境内にそびえる樹齢約400年・樹高約27mの「蓮花院のムク」は昭和19年(1944年)に埼玉県指定天然記念物に指定。
