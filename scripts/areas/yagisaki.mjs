// 八木崎（やぎさき）エリア定義（浜川戸砂丘・春日部八幡神社・春日部氏ゆかりの古刹をめぐる物語）
// 出典:
// - 八木崎の地名由来: 明治初年の地誌『春日部記草』に「かつて大木の杉が8本あり、海辺（干潟）だった名残から八木崎と名付けられた」と伝わる。元禄10年(1697年)の検地帳にも「八木崎耕地」として記録（『角川日本地名大辞典 11 埼玉県』・春日部市郷土資料館）。
// - 浜川戸砂丘: 平安時代〜室町時代の寒冷期に、浅間山や榛名山の火山灰を含む砂が季節風によって旧利根川（古隅田川）沿いに吹き溜まって形成された内陸の河畔砂丘。2016年(平成28年)に埼玉県指定天然記念物（「中川低地の河畔砂丘群 浜川戸砂丘」）に指定。
// - 春日部八幡神社（春日部市粕壁5597）: 鎌倉時代末期の元弘年間(1331〜1334年頃)、新田義貞に従った武将・春日部重行公が相模国の鶴岡八幡宮を勧請して創建したと伝わる。新方四十余郷の総鎮守。隣接する春日部稲荷神社は寛元年間(1243〜1247年頃)に春日部実景が伏見稲荷を屋敷神として勧請したと伝わり、一帯は中世の春日部氏館跡（浜川戸遺跡）にあたる。
// - 愛宕山 成就院（春日部市粕壁3-9-28）: 真言宗智山派。寺伝では弘仁11年(820年)真済僧正開創、慶長年間(1596〜1615年)順清和尚中興。もとは浜川戸耕地にあり、元禄8年(1695年)に現在地へ移転。境内に天明の大飢饉等で宿場を救った名主・見川喜蔵の墓および見川家五輪塔（市指定文化財）がある。
// - 華林山 最勝院（春日部市粕壁3-9-20）: 真言宗智山派。永正元年(1504年)に慈恩寺の僧・奝尊が草庵を結んだことに始まり、慶安元年(1649年)に徳川幕府から寺領15石の御朱印状を拝領。本堂西側に、延元元年(1336年)に京都・鷺の森で南朝方として自刃した春日部重行公の遺骨を長男・家縄らが持ち帰り葬ったと伝わる墳墓（御霊古墳）がある。
